#!/usr/bin/env bash
# lib/report.sh — JSON → Markdown report generation

generate_report() {
    local results_dir="$1"
    local report_file="$results_dir/BENCHMARK-REPORT.md"

    info "Generating benchmark report..."

    # ─── Header ────────────────────────────────────────────────────────────
    cat > "$report_file" <<'HEADER'
# ClawCompare Benchmark Report

> Auto-generated by `bench/run-all.sh`

HEADER

    # ─── System Info ───────────────────────────────────────────────────────
    if [[ -f "$results_dir/system-info.json" ]]; then
        local sys
        sys="$(cat "$results_dir/system-info.json")"
        cat >> "$report_file" <<EOF
## System Information

| Property | Value |
|----------|-------|
| Platform | $(echo "$sys" | jq -r '.platform') $(echo "$sys" | jq -r '.arch') |
| OS | $(echo "$sys" | jq -r '.os_version') |
| CPU | $(echo "$sys" | jq -r '.cpu') |
| Cores | $(echo "$sys" | jq -r '.cores') |
| RAM | $(echo "$sys" | jq -r '.ram_gb') GB |
| Date | $(date -u '+%Y-%m-%d %H:%M UTC') |

EOF
    fi

    # ─── Tool versions ─────────────────────────────────────────────────────
    if [[ -f "$results_dir/00-preflight.json" ]]; then
        local pf
        pf="$(cat "$results_dir/00-preflight.json")"
        cat >> "$report_file" <<EOF
### Toolchain Versions

| Tool | Version |
|------|---------|
EOF
        echo "$pf" | jq -r '.tools // {} | to_entries[] | "| \(.key) | \(.value) |"' >> "$report_file"
        echo "" >> "$report_file"

        # Build status
        cat >> "$report_file" <<EOF
### Build Status

| Project | Status |
|---------|--------|
EOF
        for proj in openclaw zeroclaw picoclaw; do
            local status
            status="$(echo "$pf" | jq -r ".builds.${proj} // \"skipped\"")"
            local icon="⏭️"
            [[ "$status" == "ok" ]] && icon="✅"
            [[ "$status" == "failed" ]] && icon="❌"
            echo "| $proj | $icon $status |" >> "$report_file"
        done
        echo "" >> "$report_file"
    fi

    # ─── Static Metrics ────────────────────────────────────────────────────
    if [[ -f "$results_dir/01-static.json" ]]; then
        local st
        st="$(cat "$results_dir/01-static.json")"
        cat >> "$report_file" <<'EOF'
## Static Metrics

### Binary / Artifact Size

| Project | Size | Human |
|---------|-----:|-------|
EOF
        for proj in openclaw zeroclaw picoclaw; do
            local size human
            size="$(echo "$st" | jq -r ".binary_size.${proj}.bytes // \"-\"")"
            human="$(echo "$st" | jq -r ".binary_size.${proj}.human // \"-\"")"
            echo "| $proj | $size | $human |" >> "$report_file"
        done

        cat >> "$report_file" <<'EOF'

### Dependency Count

| Project | Dependencies |
|---------|-------------:|
EOF
        for proj in openclaw zeroclaw picoclaw; do
            local deps
            deps="$(echo "$st" | jq -r ".dependencies.${proj} // \"-\"")"
            echo "| $proj | $deps |" >> "$report_file"
        done

        cat >> "$report_file" <<'EOF'

### Source Lines of Code

| Project | SLOC |
|---------|-----:|
EOF
        for proj in openclaw zeroclaw picoclaw; do
            local sloc
            sloc="$(echo "$st" | jq -r ".sloc.${proj} // \"-\"")"
            echo "| $proj | $sloc |" >> "$report_file"
        done
        echo "" >> "$report_file"
    fi

    # ─── Startup Timing ───────────────────────────────────────────────────
    if [[ -f "$results_dir/02-startup.json" ]]; then
        local su
        su="$(cat "$results_dir/02-startup.json")"
        cat >> "$report_file" <<'EOF'
## Startup Timing

### `--version` Flag (ms)

| Project | Min | Median | Mean | P95 | Max |
|---------|----:|-------:|-----:|----:|----:|
EOF
        for proj in openclaw zeroclaw picoclaw; do
            local stats
            stats="$(echo "$su" | jq -c ".version_flag.${proj}.stats // {}")"
            if [[ "$stats" != "{}" && "$stats" != "null" ]]; then
                echo "| $proj | $(echo "$stats" | jq -r '.min') | $(echo "$stats" | jq -r '.median') | $(echo "$stats" | jq -r '.mean') | $(echo "$stats" | jq -r '.p95') | $(echo "$stats" | jq -r '.max') |" >> "$report_file"
            fi
        done

        # Relative comparison bar chart
        cat >> "$report_file" <<'EOF'

#### Relative Startup Time

EOF
        local min_median=999999
        for proj in openclaw zeroclaw picoclaw; do
            local med
            med="$(echo "$su" | jq -r ".version_flag.${proj}.stats.median // 999999")"
            if (( $(echo "$med < $min_median" | bc -l) )); then
                min_median="$med"
            fi
        done

        for proj in openclaw zeroclaw picoclaw; do
            local med ratio bar_len bar
            med="$(echo "$su" | jq -r ".version_flag.${proj}.stats.median // 0")"
            if [[ "$med" != "0" && "$min_median" != "0" ]]; then
                ratio="$(echo "scale=1; $med / $min_median" | bc)"
                bar_len="$(echo "$ratio * 10" | bc | cut -d. -f1)"
                bar="$(printf '█%.0s' $(seq 1 "${bar_len:-1}"))"
                echo "- **$proj**: ${bar} ${med}ms (${ratio}x)" >> "$report_file"
            fi
        done
        echo "" >> "$report_file"
    fi

    # ─── Build Times ──────────────────────────────────────────────────────
    if [[ -f "$results_dir/03-build.json" ]]; then
        local bd
        bd="$(cat "$results_dir/03-build.json")"
        cat >> "$report_file" <<'EOF'
## Build Times

### Clean Build (ms)

| Project | Time | Human |
|---------|-----:|-------|
EOF
        for proj in openclaw zeroclaw picoclaw; do
            local t h
            t="$(echo "$bd" | jq -r ".clean_build.${proj}.ms // \"-\"")"
            h="$(echo "$bd" | jq -r ".clean_build.${proj}.human // \"-\"")"
            echo "| $proj | $t | $h |" >> "$report_file"
        done

        cat >> "$report_file" <<'EOF'

### Incremental Build (ms)

| Project | Time | Human |
|---------|-----:|-------|
EOF
        for proj in openclaw zeroclaw picoclaw; do
            local t h
            t="$(echo "$bd" | jq -r ".incremental_build.${proj}.ms // \"-\"")"
            h="$(echo "$bd" | jq -r ".incremental_build.${proj}.human // \"-\"")"
            echo "| $proj | $t | $h |" >> "$report_file"
        done
        echo "" >> "$report_file"
    fi

    # ─── Runtime Memory ───────────────────────────────────────────────────
    if [[ -f "$results_dir/04-memory.json" ]]; then
        local mem
        mem="$(cat "$results_dir/04-memory.json")"
        cat >> "$report_file" <<'EOF'
## Runtime Memory (Peak RSS)

| Project | RSS (KB) | RSS (MB) |
|---------|--------:|--------:|
EOF
        for proj in openclaw zeroclaw picoclaw; do
            local kb mb
            kb="$(echo "$mem" | jq -r ".peak_rss.${proj}.kb // \"-\"")"
            mb="$(echo "$mem" | jq -r ".peak_rss.${proj}.mb // \"-\"")"
            echo "| $proj | $kb | $mb |" >> "$report_file"
        done
        echo "" >> "$report_file"
    fi

    # ─── Roundtrip Latency ────────────────────────────────────────────────
    if [[ -f "$results_dir/05-latency.json" ]]; then
        local lat
        lat="$(cat "$results_dir/05-latency.json")"
        cat >> "$report_file" <<'EOF'
## Roundtrip Latency (ms)

| Project | Min | Median | Mean | P95 | Max |
|---------|----:|-------:|-----:|----:|----:|
EOF
        for proj in openclaw zeroclaw picoclaw; do
            local stats
            stats="$(echo "$lat" | jq -c ".roundtrip.${proj}.stats // {}")"
            if [[ "$stats" != "{}" && "$stats" != "null" ]]; then
                echo "| $proj | $(echo "$stats" | jq -r '.min') | $(echo "$stats" | jq -r '.median') | $(echo "$stats" | jq -r '.mean') | $(echo "$stats" | jq -r '.p95') | $(echo "$stats" | jq -r '.max') |" >> "$report_file"
            fi
        done
        echo "" >> "$report_file"
    fi

    # ─── Stress / Compaction ──────────────────────────────────────────────
    if [[ -f "$results_dir/06-stress.json" ]]; then
        local stress
        stress="$(cat "$results_dir/06-stress.json")"
        cat >> "$report_file" <<'EOF'
## Memory Under Load (Stress Test)

### RSS Growth by Message Count (KB)

| Project | 5 msgs | 10 msgs | 20 msgs | 50 msgs |
|---------|-------:|--------:|--------:|--------:|
EOF
        for proj in openclaw zeroclaw picoclaw; do
            local r5 r10 r20 r50
            r5="$(echo "$stress" | jq -r ".growth.${proj}[\"5\"] // \"-\"")"
            r10="$(echo "$stress" | jq -r ".growth.${proj}[\"10\"] // \"-\"")"
            r20="$(echo "$stress" | jq -r ".growth.${proj}[\"20\"] // \"-\"")"
            r50="$(echo "$stress" | jq -r ".growth.${proj}[\"50\"] // \"-\"")"
            echo "| $proj | $r5 | $r10 | $r20 | $r50 |" >> "$report_file"
        done

        cat >> "$report_file" <<'EOF'

### Compaction Events

EOF
        for proj in openclaw zeroclaw picoclaw; do
            local compaction
            compaction="$(echo "$stress" | jq -r ".compaction.${proj} // {}")"
            if [[ "$compaction" != "{}" && "$compaction" != "null" ]]; then
                local detected at_msg before after
                detected="$(echo "$compaction" | jq -r '.detected // false')"
                if [[ "$detected" == "true" ]]; then
                    at_msg="$(echo "$compaction" | jq -r '.at_message // "?"')"
                    before="$(echo "$compaction" | jq -r '.rss_before_kb // "?"')"
                    after="$(echo "$compaction" | jq -r '.rss_after_kb // "?"')"
                    echo "- **$proj**: Compaction detected at message $at_msg (RSS: ${before} KB → ${after} KB)" >> "$report_file"
                else
                    echo "- **$proj**: No compaction detected" >> "$report_file"
                fi
            fi
        done
        echo "" >> "$report_file"
    fi

    # ─── Key Findings ─────────────────────────────────────────────────────
    cat >> "$report_file" <<'EOF'
## Key Findings

EOF
    _generate_findings "$results_dir" >> "$report_file"

    # ─── Footer ────────────────────────────────────────────────────────────
    cat >> "$report_file" <<EOF

---

*Generated on $(date -u '+%Y-%m-%d %H:%M:%S UTC') by \`bench/run-all.sh\`*
EOF

    ok "Report written to $report_file"
}

_generate_findings() {
    local results_dir="$1"

    # Startup speed winner
    if [[ -f "$results_dir/02-startup.json" ]]; then
        local su fastest fastest_ms
        su="$(cat "$results_dir/02-startup.json")"
        fastest=""
        fastest_ms=999999

        for proj in openclaw zeroclaw picoclaw; do
            local med
            med="$(echo "$su" | jq -r ".version_flag.${proj}.stats.median // 999999")"
            if (( $(echo "$med < $fastest_ms" | bc -l) )); then
                fastest_ms="$med"
                fastest="$proj"
            fi
        done

        if [[ -n "$fastest" ]]; then
            echo "- **Fastest startup**: $fastest at ${fastest_ms}ms median"
        fi
    fi

    # Smallest binary
    if [[ -f "$results_dir/01-static.json" ]]; then
        local st smallest smallest_bytes
        st="$(cat "$results_dir/01-static.json")"
        smallest=""
        smallest_bytes=999999999999

        for proj in openclaw zeroclaw picoclaw; do
            local b
            b="$(echo "$st" | jq -r ".binary_size.${proj}.bytes // 999999999999")"
            if (( b < smallest_bytes )); then
                smallest_bytes="$b"
                smallest="$proj"
            fi
        done

        if [[ -n "$smallest" ]]; then
            local human
            human="$(echo "$st" | jq -r ".binary_size.${smallest}.human // \"?\"")"
            echo "- **Smallest artifact**: $smallest at $human"
        fi
    fi

    # Lowest memory
    if [[ -f "$results_dir/04-memory.json" ]]; then
        local mem leanest leanest_kb
        mem="$(cat "$results_dir/04-memory.json")"
        leanest=""
        leanest_kb=999999999

        for proj in openclaw zeroclaw picoclaw; do
            local kb
            kb="$(echo "$mem" | jq -r ".peak_rss.${proj}.kb // 999999999")"
            if (( kb < leanest_kb )); then
                leanest_kb="$kb"
                leanest="$proj"
            fi
        done

        if [[ -n "$leanest" ]]; then
            local mb
            mb="$(echo "$mem" | jq -r ".peak_rss.${leanest}.mb // \"?\"")"
            echo "- **Lowest memory**: $leanest at ${mb} MB peak RSS"
        fi
    fi

    # Fewest dependencies
    if [[ -f "$results_dir/01-static.json" ]]; then
        local st fewest fewest_deps
        st="$(cat "$results_dir/01-static.json")"
        fewest=""
        fewest_deps=999999

        for proj in openclaw zeroclaw picoclaw; do
            local d
            d="$(echo "$st" | jq -r ".dependencies.${proj} // 999999")"
            if (( d < fewest_deps )); then
                fewest_deps="$d"
                fewest="$proj"
            fi
        done

        if [[ -n "$fewest" ]]; then
            echo "- **Fewest dependencies**: $fewest with $fewest_deps direct dependencies"
        fi
    fi
}
